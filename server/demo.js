function lastUser(messages = []) {
  for (let i = messages.length - 1; i >= 0; i--) if (messages[i].role === 'user') return messages[i].content || '';
  return '';
}

function demoTitle(idea) {
  const words = String(idea)
    .replace(/[^a-zA-Z0-9 ]/g, ' ')
    .split(/\s+/)
    .filter((w) => w && !/^(a|an|the|my|with|for|and|app|website|project)$/i.test(w))
    .slice(0, 3)
    .join(' ');
  return words ? words.replace(/\b\w/g, (c) => c.toUpperCase()) : 'Nova Project';
}

function pickFlavor(body) {
  const sys = (body.messages || []).find((m) => m.role === 'system')?.content || '';
  if (/UPGRADE PLANNER/i.test(sys)) return 'uplanner';
  if (/UPGRADE BUILDER/i.test(sys)) return 'ubuilder';
  if (/UPGRADE REPORT/i.test(sys)) return 'ureport';
  if (/COORDINATOR/i.test(sys)) return 'coordinator';
  if (/FILE BUILDER/i.test(sys)) return 'builder';
  if (/TESTER/i.test(sys)) return 'tester';
  if (/DEBUGGER/i.test(sys)) return 'debugger';
  if (/DOCUMENTER/i.test(sys)) return 'documenter';
  if (/OPTIMIZER/i.test(sys)) return 'reporter';
  if (/PLANNER/i.test(sys)) return 'planner';
  if (/REVIEW AGENT/i.test(sys)) return 'critic';
  if (/SYNTHESIS AGENT/i.test(sys)) return 'synth';
  if (/qwen-coder|coder/i.test(body.model || '')) return 'coder';
  return 'worker';
}

export function demoResponse(body) {
  const raw = lastUser(body.messages);
  const q = raw.slice(0, 400);
  const topic = q.replace(/\s+/g, ' ').trim() || 'your request';
  const flavor = pickFlavor(body);

  // ── project pipeline roles ────────────────────────────────────────────────
  if (flavor === 'uplanner') {
    const reqq = (String(q).split(/UPGRADE REQUEST:/i)[1] || '').split('\n')[0].trim();
    const paths = [...String(q).matchAll(/^- (\S+)$/gm)].map((m) => m[1]);
    const html = paths.find((p) => /\.html?$/i.test(p));
    const css = paths.find((p) => /\.css$/i.test(p));
    const js = paths.find((p) => /\.m?js$/i.test(p));
    const changes = [];
    if (html) changes.push({ action: 'modify', path: html, instruction: reqq });
    if (css && /style|design|color|theme|dark|look|polish/i.test(reqq)) changes.push({ action: 'modify', path: css, instruction: reqq });
    if (js && /sound|feature|interact|animat|button|score|game|effect|mobile|touch/i.test(reqq)) changes.push({ action: 'modify', path: js, instruction: reqq });
    if (!changes.length && js) changes.push({ action: 'modify', path: js, instruction: reqq });
    return JSON.stringify({ summary: `Applying your upgrade: ${reqq.slice(0, 80)}`, changes });
  }

  if (flavor === 'ubuilder') {
    const m = String(raw).match(/---CURRENT FILE CONTENT---\n([\s\S]*?)\n---END CURRENT FILE CONTENT---/);
    const path = (String(q).match(/FILE: (\S+)/) || [])[1] || 'file.txt';
    const current = m ? m[1] : '';
    if (/\.m?js$/i.test(path)) return (current || '// new module') + `\nconsole.info('[nexus] upgrade applied');`;
    if (/\.css$/i.test(path)) return (current || '/* styles */') + `\n/* nexus upgrade applied */`;
    return (current || '<!-- new file -->') + `\n<!-- nexus upgrade applied -->`;
  }

  if (flavor === 'ureport') {
    const reqq = (String(q).split(/UPGRADE REQUEST:/i)[1] || '').split('\n')[0].trim();
    const files = (String(q).split(/Files updated:\s*/i)[1] || '').split('\n')[0].trim();
    return `## What changed\n- Applied: “${reqq.slice(0, 100)}”\n- Updated: ${files || 'project files'}\n- Re-tested the project — all checks pass.\n\n*Upgrade note by the NexusAI demo team.*`;
  }

  if (flavor === 'coordinator') {
    const idea = (String(q).split(/PROJECT IDEA:/i)[1] || q).replace(/\s+/g, ' ').trim();
    const title = demoTitle(idea);
    return JSON.stringify({
      title,
      description: `A self-contained web app: ${idea.slice(0, 90)}`,
      stack: ['html', 'css', 'js'],
      files: [
        { path: 'index.html', purpose: 'page structure and layout' },
        { path: 'css/style.css', purpose: 'all styling and theming' },
        { path: 'js/app.js', purpose: 'interactivity and state' },
      ],
      steps: ['structure first', 'then styling', 'then logic', 'test and polish'],
    });
  }

  if (flavor === 'builder') {
    const path = (String(q).match(/PROJECT FILE:\s*(\S+)/) || [])[1] || 'index.html';
    const title = (String(q).match(/PROJECT:\s*(.+?)(?:\n|—)/) || [])[1] || 'Nova Project';
    if (/\.html?$/i.test(path)) return P_HTML(title.trim() || 'Nova Project');
    if (/\.css$/i.test(path)) return P_CSS;
    if (/\.m?js$/i.test(path)) return P_JS_BUGGY;
    if (/\.md$/i.test(path)) return P_README(title.trim() || 'Nova Project');
    return `# ${path}\n(generated by the NexusAI demo builder)`;
  }

  if (flavor === 'tester') {
    // surgical: only report the noisy-log bug in files that actually contain it
    const blocks = [...String(raw).matchAll(/### (\S+)\n```\n([\s\S]*?)\n```/g)];
    const buggy = blocks.find((b) => /console\.log\('clicked'/.test(b[2]));
    if (!buggy) return JSON.stringify({ verdict: 'pass', bugs: [] });
    return JSON.stringify({
      verdict: 'issues',
      bugs: [{ file: buggy[1], issue: 'console.log fires on every click — noisy in production', fix: 'remove the per-click log, keep the startup log' }],
    });
  }

  if (flavor === 'debugger') {
    // surgical: strip only the noisy log lines from the current file contents
    const blocks = [...String(raw).matchAll(/### (\S+)\n```\n([\s\S]*?)\n```/g)];
    const files = [];
    for (const b of blocks) {
      if (/console\.log\('clicked'/.test(b[2])) {
        files.push({ path: b[1], content: b[2].split('\n').filter((l) => !/console\.log\('clicked'/.test(l)).join('\n') });
      }
    }
    return JSON.stringify({ files });
  }

  if (flavor === 'documenter') {
    const title = (String(q).match(/PROJECT:\s*(.+?)(?:\n|—)/) || [])[1] || 'Nova Project';
    return P_README(title.trim());
  }

  if (flavor === 'reporter') {
    const title = (String(q).match(/PROJECT:\s*(.+?)(?:\n|—)/) || [])[1] || 'Nova Project';
    return P_REPORT(title.trim());
  }

  // ── chat team roles ───────────────────────────────────────────────────────
  if (flavor === 'planner') {
    return `## Goal
Deliver a high-quality, complete answer for: “${topic}”

## Requirements
- Correct, concrete, and immediately usable
- Bold structure: clear headings, tight lists, zero filler
- Include runnable code when it helps

## Approach
1. Understand the core intent behind the question
2. Draft a direct, example-driven answer
3. Verify edge cases and state caveats honestly

## Style
Confident, precise, Markdown-formatted. Lead with the answer, then the detail.`;
  }

  if (flavor === 'critic') {
    return `## Verdict
**Draft A** is the strongest — it opens with a direct answer, its structure is the cleanest, and its examples map exactly to the request. Draft B adds useful edge-case notes worth merging.

## Merge
- **Keep (A):** opening summary, section order, code formatting
- **Keep (B):** the caveats section and the “common mistakes” list
- **Fix:** both drafts bury the key command too deep — move it to the first screen
- **Add:** a one-line “TL;DR” at the very top`;
  }

  if (flavor === 'synth') {
    return `**TL;DR — ${topic}** handled in three moves: understand → build → verify.

## The Direct Answer
Here is the strongest synthesis of the team's drafts, merged and tightened. ${
      CODE_RE.test(topic)
        ? 'Below is a complete, runnable starting point — hit **Preview** on the code block to see it live.'
        : 'The core idea first, then the working detail.'
    }

${CODE_RE.test(topic) ? '```html\n' + LANDING + '\n```' : ''}

## Why This Works
- **Bold structure** — the answer leads, the detail follows
- **Verified** — the review agent checked edge cases and caveats
- **Runnable** — everything above is copy-paste ready

## Next Steps
1. Try the suggestion above
2. Tweak it to your context
3. Ask NexusAI to iterate — the team will re-run automatically

> Synthesized offline by the **NexusAI Demo Model**. Add real keys in **Keys & Models** to power the team with DeepSeek, Qwen, Claude and GPT.`;
  }

  // workers
  const worker = (letter, angle) => `### Draft ${letter} — ${angle}

**Direct answer:** ${topic} is best approached by starting with the outcome, then working backwards to the smallest working version.

${CODE_RE.test(topic) ? '```html\n' + LANDING + '\n```\n' : ''}**Key points**
- ${angle} first — everything else follows
- Keep the first version embarrassingly small, then iterate
- Measure before optimizing

**Caveats:** test edge cases early; the obvious failure mode is skipping step one.`;

  if (flavor === 'coder') {
    return `${worker('B', 'A code-first angle')}`;
  }
  return `${worker('A', 'A clarity-first angle')}`;
}

// Stream as OpenAI-format SSE
export async function streamDemo(body, res) {
  res.status(200);
  res.setHeader('Content-Type', 'text/event-stream; charset=utf-8');
  res.setHeader('Cache-Control', 'no-cache, no-transform');
  res.setHeader('X-Accel-Buffering', 'no');
  res.flushHeaders?.();

  const text = demoResponse(body);
  const tokens = text.match(/\s*\S+/g) || [];
  const write = (obj) => res.write(`data: ${JSON.stringify(obj)}\n\n`);
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

  try {
    write({ choices: [{ delta: { role: 'assistant' } }] });
    for (const t of tokens) {
      if (res.writableEnded || res.destroyed) break;
      write({ choices: [{ delta: { content: t } }] });
      await sleep(14);
    }
    write({ choices: [{ delta: {}, finish_reason: 'stop' }] });
    res.write('data: [DONE]\n\n');
  } catch {}
  res.end();
}
